"""Generate web/src/engine/taste-catalog.ts from the Taste Picker's FAMILIES table.

    python tools/gen-taste-catalog.py <path-to-TastePicker.html>

The picker keeps its catalog as one JSON literal inside a <script> block. This script reads that
literal, so the app's genre and subgenre data is the picker's data byte-for-byte, not retyped.
"""
import json
import pathlib
import sys

src_path = pathlib.Path(sys.argv[1])
src = src_path.read_text(encoding="utf-8")
line = next(l for l in src.splitlines() if l.startswith("const FAMILIES = "))
families = json.loads(line[len("const FAMILIES = "):].rstrip(";"))

FAMILY_SOUND = {}
for l in src.splitlines():
    if l.startswith("  '") and "':'" in l:
        key, _, val = l.strip().rstrip(",").partition("':'")
        FAMILY_SOUND[key[1:]] = val.rstrip("'")

out = []
out.append("// GENERATED by tools/gen-taste-catalog.py from the Taste Picker. Do not edit by hand.")
out.append("// Tempo ranges, eras and sound notes: DJ and producer references (see the picker's footer).")
out.append("")
out.append("export interface CatalogSub {")
out.append("  name: string;")
out.append("  lo: number;")
out.append("  hi: number;")
out.append("  halftime: boolean;")
out.append("  years: string;")
out.append("  sound: string;")
out.append("  energy: number;")
out.append("  brightness: number;")
out.append("  artists: string[];")
out.append("}")
out.append("")
out.append("export interface CatalogFamily {")
out.append("  name: string;")
out.append("  sound: string;")
out.append("  subs: CatalogSub[];")
out.append("}")
out.append("")
out.append("export const CATALOG: CatalogFamily[] = [")
for f in families:
    out.append("  {")
    out.append(f"    name: {json.dumps(f['name'])},")
    out.append(f"    sound: {json.dumps(FAMILY_SOUND.get(f['name'], ''))},")
    out.append("    subs: [")
    for s in f["s"]:
        name, lo, hi, half, years, sound, energy, bright, artists = s
        out.append("      {")
        out.append(f"        name: {json.dumps(name)}, lo: {lo}, hi: {hi}, halftime: {'true' if half else 'false'},")
        out.append(f"        years: {json.dumps(years)}, energy: {energy}, brightness: {bright},")
        out.append(f"        sound: {json.dumps(sound)},")
        out.append(f"        artists: {json.dumps(artists)},")
        out.append("      },")
    out.append("    ],")
    out.append("  },")
out.append("];")
out.append("")

dest = pathlib.Path(__file__).resolve().parent.parent / "web" / "src" / "engine" / "taste-catalog.ts"
dest.write_text("\n".join(out) + "\n", encoding="utf-8")
n = sum(len(f["s"]) for f in families)
print(f"wrote {dest} : {len(families)} families, {n} subgenres")
